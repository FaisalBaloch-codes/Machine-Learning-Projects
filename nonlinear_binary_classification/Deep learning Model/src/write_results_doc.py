"""
write_results_doc.py
---------------------
Writes docs/results.md using the REAL numbers produced by training and
evaluation (read from the CSV files already saved on disk). This guarantees
the documentation never contains made-up numbers.
"""

import pandas as pd

from config import (
    FULL_DATASET_CSV,
    TRAIN_CSV,
    TEST_CSV,
    TRAINING_HISTORY_CSV,
    EVALUATION_METRICS_CSV,
    HIDDEN_LAYER_UNITS,
    HIDDEN_LAYER_ACTIVATIONS,
    OUTPUT_ACTIVATION,
    RESULTS_MD,
)


def main():
    full_df = pd.read_csv(FULL_DATASET_CSV)
    train_df = pd.read_csv(TRAIN_CSV)
    test_df = pd.read_csv(TEST_CSV)
    history_df = pd.read_csv(TRAINING_HISTORY_CSV)
    metrics_df = pd.read_csv(EVALUATION_METRICS_CSV)

    epochs_trained = int(history_df["epoch"].max())
    metrics = metrics_df.iloc[0].to_dict()

    def pct(v):
        return f"{v * 100:.2f}%"

    def fnum(v):
        return f"{v:.4f}"

    performance_comment = (
        "The model performs very well: it correctly separates the two "
        "interleaving moon shapes and achieves high accuracy, precision, "
        "recall and AUC on data it never saw during training. This shows "
        "that the network genuinely learned the nonlinear pattern rather "
        "than memorizing the training data."
        if metrics["test_accuracy"] >= 0.85 else
        "The model shows reasonable performance but there is room for "
        "improvement — for example by training longer, tuning the "
        "learning rate, or adjusting the noise level of the dataset."
    )

    content = f"""# Results

All numbers on this page were generated by actually running the project
(`python src/run_pipeline.py`) — nothing here is guessed or invented.

## Dataset Summary

| Item | Value |
|---|---|
| Total samples | {len(full_df)} |
| Features | 2 (`x`, `y`) |
| Training samples | {len(train_df)} |
| Testing samples | {len(test_df)} |
| Class balance (full dataset) | Class 0: {int((full_df['target']==0).sum())}, Class 1: {int((full_df['target']==1).sum())} |

## Model Architecture

| Layer | Neurons | Activation |
|---|---|---|
| Hidden Layer 1 | {HIDDEN_LAYER_UNITS} | {HIDDEN_LAYER_ACTIVATIONS[0]} |
| Hidden Layer 2 | {HIDDEN_LAYER_UNITS} | {HIDDEN_LAYER_ACTIVATIONS[1]} |
| Hidden Layer 3 | {HIDDEN_LAYER_UNITS} | {HIDDEN_LAYER_ACTIVATIONS[2]} |
| Hidden Layer 4 | {HIDDEN_LAYER_UNITS} | {HIDDEN_LAYER_ACTIVATIONS[3]} |
| Output Layer | 1 | {OUTPUT_ACTIVATION} |

* Optimizer: **Adam**
* Loss function: **binary_crossentropy**
* Epochs actually trained (EarlyStopping may stop before the max): **{epochs_trained}**

## Test Set Results

| Metric | Value |
|---|---|
| Test Loss | {fnum(metrics['test_loss'])} |
| Test Accuracy | {pct(metrics['test_accuracy'])} |
| Precision | {fnum(metrics['precision'])} |
| Recall | {fnum(metrics['recall'])} |
| F1-score | {fnum(metrics['f1_score'])} |
| AUC | {fnum(metrics['auc'])} |

## Interpretation

{performance_comment}

See `plots/06_confusion_matrix.png` for the breakdown of correct/incorrect
predictions, and `plots/07_decision_boundary.png` to visually confirm that
the network learned a **curved (nonlinear)** boundary rather than a straight
line.
"""

    with open(RESULTS_MD, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"Results documentation written to: {RESULTS_MD}")


if __name__ == "__main__":
    main()
