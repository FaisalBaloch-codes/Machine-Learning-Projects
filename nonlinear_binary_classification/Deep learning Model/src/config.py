"""
config.py
---------
Central place for constants and folder paths used by every script in this
project. Keeping these settings in one file means that if you ever want to
change something (like the random seed, or the number of samples), you only
have to change it here instead of hunting through many files.

Beginner note:
    `pathlib.Path` is used instead of plain strings because it automatically
    works on Windows, macOS and Linux. It also lets us build paths like
    `BASE_DIR / "data" / "file.csv"` which is easier to read than gluing
    strings together with slashes or backslashes.
"""

